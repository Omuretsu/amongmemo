'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const script = fs.readFileSync(path.join(root, 'js/app.js'), 'utf8');
const styles = fs.readFileSync(path.join(root, 'css/style.css'), 'utf8');
const referencedIds = [...script.matchAll(/\$\('#([^']+)'\)/g)].map(match => match[1]);
const htmlIds = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]));
const missingIds = [...new Set(referencedIds)].filter(id => !htmlIds.has(id));

assert.deepEqual(missingIds, []);
assert.doesNotMatch(html, /data-roster-(?:player|host)[^>]*type="(?:checkbox|radio)"/);
assert.match(html, /id="rosterCount"/);
assert.match(script, /updateRosterCount\(\)/);
assert.match(styles, /#rosterDialog \{[^}]*width:min\(80vw,124vh\)[^}]*height:min\(80vh,51\.6vw\)[^}]*aspect-ratio:1\.55\/1/);
assert.match(styles, /#meetingDialog \{[^}]*width:min\(80vw,124vh\)[^}]*height:min\(80vh,51\.6vw\)[^}]*aspect-ratio:1\.55\/1/);
assert.match(styles, /#meetingDialog\[open\] \{[^}]*grid-template-rows:auto minmax\(0,1fr\) auto/);
assert.doesNotMatch(html, /id="meetingType"/);
assert.doesNotMatch(html, /id="reporter"/);
assert.match(html, /id="meetingTypeLabel"/);
assert.match(html, /id="meetingReporterList"/);
assert.match(script, /pendingMeeting=\{type,reporter:'',killOccurred:type==='report'\?true:null,victim:''\}/);
assert.match(script, /meetingShortcutLabel = number => number<=9 \? String\(number\) : number===10 \? '0' : `⇧\$\{number-10\}`/);
assert.match(script, /event\.code==='Digit0'/);
assert.match(script, /10\+Number\(match\[1\]\)/);
assert.match(script, /selectMeetingReporter\(player\.id\)/);
assert.match(styles, /\.meeting-person-list \{[^}]*grid-template-columns:repeat\(3,minmax\(0,1fr\)\)/);
assert.match(html, /id="meetingKillStep"/);
assert.match(html, /data-meeting-kill="yes"/);
assert.match(html, /data-meeting-kill="no"/);
assert.match(html, /id="meetingVictimList"/);
assert.match(script, /selectMeetingKillOccurred\(event\.code==='Digit1'\)/);
assert.match(script, /selectMeetingVictim\(player\.id\)/);
assert.match(script, /Number\(unavailableVictim\(left\)\)-Number\(unavailableVictim\(right\)\)/);
assert.match(script, /disabled aria-disabled="true"/);
assert.match(styles, /\.roster-list \{[^}]*grid-template-columns:repeat\(3,minmax\(0,1fr\)\)/);
assert.match(html, /id="shortcutToggle"/);
assert.match(script, /if \(!state\.shortcutsEnabled\) return;/);
assert.match(script, /state\.shortcutsEnabled=!state\.shortcutsEnabled/);
assert.match(script, /item\.kind==='meeting' && item\.type==='button' && item\.reporter/);
assert.match(script, /buttonUsers\.has\(player\.id\)/);
assert.match(script, /meeting-button-used/);
assert.match(script, /event\.code==='Digit4'/);
assert.doesNotMatch(script, /event\.key==='4'/);
console.log(`DOM references: ok (${new Set(referencedIds).size} ids)`);
